/**
 * Generates api/src/oracles/iching-data.ts from the web app's data files.
 *
 * The corpus lives in web/assets/data/ as browser globals so the static oracle
 * can load it with plain <script> tags and no build step. The API needs the
 * same texts as a typed module. One source, two shapes — run this after
 * editing any hexagram text.
 *
 *   node scripts/build-corpus.mjs
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dataDir = path.resolve(here, "../../web/assets/data");
const outFile = path.resolve(here, "../src/oracles/iching-data.ts");

globalThis.window = {};
for (const f of ["hex-01-16", "hex-17-32", "hex-33-48", "hex-49-64", "trigrams"]) {
  const src = fs.readFileSync(path.join(dataDir, `${f}.js`), "utf8");
  (0, eval)(src);
}

const all = [
  ...globalThis.window.HEX_1, ...globalThis.window.HEX_2,
  ...globalThis.window.HEX_3, ...globalThis.window.HEX_4,
];

if (all.length !== 64) throw new Error(`expected 64 hexagrams, got ${all.length}`);
const patterns = new Set(all.map((h) => h.lines));
if (patterns.size !== 64) throw new Error(`expected 64 unique patterns, got ${patterns.size}`);
for (const h of all) {
  if (h.lines6?.length !== 6) throw new Error(`hexagram ${h.n} does not have 6 line texts`);
}

fs.writeFileSync(outFile, `/* GENERATED by scripts/build-corpus.mjs — do not edit by hand.
 * Source of truth: web/assets/data/hex-*.js
 *
 * Interpretive text original to Liber 488. Not a translation. */

export interface Hexagram {
  n: number; lines: string; zh: string; py: string; en: string;
  judgment: string; image: string; counsel: string; lines6: string[];
}

export interface Trigram { zh: string; py: string; en: string; glyph: string; attr: string; image: string; }

export const HEXAGRAMS: Hexagram[] = ${JSON.stringify(all, null, 2)};

export const TRIGRAMS: Record<string, Trigram> = ${JSON.stringify(globalThis.window.TRIGRAMS, null, 2)};

export const BY_PATTERN: Record<string, Hexagram> =
  Object.fromEntries(HEXAGRAMS.map((h) => [h.lines, h]));
`);

console.log(`corpus: ${all.length} hexagrams, ${all.reduce((a, h) => a + h.lines6.length, 0)} line texts -> ${path.relative(process.cwd(), outFile)}`);
